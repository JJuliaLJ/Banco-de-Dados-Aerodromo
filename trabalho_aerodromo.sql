
BEGIN;

-- 1. UF: a fonte fornece apenas a sigla, sem nomes completos de estados.
CREATE TABLE estado (
    estado_id CHAR(2) PRIMARY KEY,
    CONSTRAINT ck_estado_id CHECK (estado_id ~ '^[A-Z]{2}$')
);

-- 2. Municipio: a mesma entidade representa localizacao e municipio servido.
CREATE TABLE municipio (
    municipio_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    estado_id CHAR(2) NOT NULL REFERENCES estado(estado_id),
    CONSTRAINT uq_municipio_nome_estado UNIQUE (nome, estado_id),
    CONSTRAINT ck_municipio_nome CHECK (
        btrim(nome) <> '' AND nome = upper(nome)
        AND octet_length(nome) = char_length(nome)
    )
);
CREATE INDEX idx_municipio_estado ON municipio(estado_id);

-- 3. Valores de dominio extraidos EXCLUSIVAMENTE do CSV.
CREATE TABLE superficie_pista (
    superficie_pista_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT ck_superficie_texto CHECK (
        descricao = upper(descricao) AND octet_length(descricao) = char_length(descricao)
    )
);

CREATE TABLE tipo_operacao (
    tipo_operacao_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla VARCHAR(15) NOT NULL UNIQUE,
    CONSTRAINT ck_tipo_operacao_sigla CHECK (sigla IN ('VFR', 'IFR', 'SEM OPERACAO'))
);

CREATE TABLE perfil_operacional (
    perfil_operacional_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(40) NOT NULL UNIQUE,
    CONSTRAINT ck_perfil_texto CHECK (
        descricao = upper(descricao) AND octet_length(descricao) = char_length(descricao)
    )
);

CREATE TABLE categoria_operacao (
    categoria_operacao_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(120) NOT NULL UNIQUE,
    CONSTRAINT ck_categoria_texto CHECK (
        descricao = upper(descricao) AND octet_length(descricao) = char_length(descricao)
    )
);

CREATE TABLE restricao (
    restricao_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao TEXT NOT NULL UNIQUE,
    CONSTRAINT ck_restricao_texto CHECK (
        btrim(descricao) <> '' AND descricao = upper(descricao)
        AND octet_length(descricao) = char_length(descricao)
    )
);

-- 4. Entidade principal: mantem o ID original da ANAC e dados atomicos.
CREATE TABLE aerodromo (
    aerodromo_id INTEGER PRIMARY KEY,
    ciad CHAR(6) NOT NULL UNIQUE,
    codigo_oaci CHAR(4) UNIQUE,
    nome VARCHAR(100) NOT NULL,
    tipo_uso VARCHAR(10), -- 3 NULL no CSV; nao inventar classificacao.
    municipio_id INTEGER NOT NULL REFERENCES municipio(municipio_id),
    municipio_servido_id INTEGER REFERENCES municipio(municipio_id),
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    altitude_m NUMERIC(7,1),
    situacao VARCHAR(15) NOT NULL,
    certificacao_operacional BOOLEAN NOT NULL,
    amazonia_legal BOOLEAN NOT NULL,
    validade_cadastro DATE,
    link_portaria_cadastro TEXT,
    CONSTRAINT ck_aerodromo_ciad CHECK (ciad ~ '^[A-Z]{2}[0-9]{4}$'),
    CONSTRAINT ck_aerodromo_oaci CHECK (codigo_oaci ~ '^[A-Z0-9]{4}$'),
    CONSTRAINT ck_aerodromo_nome CHECK (
        btrim(nome) <> '' AND nome = upper(nome)
        AND octet_length(nome) = char_length(nome)
    ),
    CONSTRAINT ck_aerodromo_uso CHECK (tipo_uso IN ('PUBLICO', 'PRIVADO')),
    CONSTRAINT ck_aerodromo_situacao CHECK (
        situacao IN ('CADASTRADO', 'AUTORIZADO', 'INTERDITADO')
    ),
    CONSTRAINT ck_aerodromo_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_aerodromo_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_aerodromo_altitude CHECK (altitude_m >= 0),
    CONSTRAINT ck_aerodromo_portaria CHECK (link_portaria_cadastro ~ '^https?://')
);
CREATE INDEX idx_aerodromo_municipio ON aerodromo(municipio_id);
CREATE INDEX idx_aerodromo_municipio_servido ON aerodromo(municipio_servido_id);
CREATE INDEX idx_aerodromo_nome ON aerodromo(nome);
CREATE INDEX idx_aerodromo_situacao ON aerodromo(situacao);
CREATE INDEX idx_aerodromo_tipo_uso ON aerodromo(tipo_uso);
CREATE INDEX idx_aerodromo_validade ON aerodromo(validade_cadastro);

-- 5. Pista: entidade separada, com ID original (relacao 1:N possivel).
CREATE TABLE pista (
    pista_id INTEGER PRIMARY KEY,
    aerodromo_id INTEGER NOT NULL REFERENCES aerodromo(aerodromo_id) ON DELETE CASCADE,
    designacao VARCHAR(7) NOT NULL,
    comprimento_m NUMERIC(6,1) NOT NULL,
    largura_m NUMERIC(4,1) NOT NULL,
    superficie_pista_id INTEGER NOT NULL REFERENCES superficie_pista(superficie_pista_id),
    resistencia_kg NUMERIC(7,1),
    resistencia_mpa NUMERIC(5,2),
    resistencia_pcn VARCHAR(15),
    luzes_eixo BOOLEAN,
    luzes_borda BOOLEAN,
    CONSTRAINT uq_pista_aerodromo_designacao UNIQUE (aerodromo_id, designacao),
    CONSTRAINT ck_pista_designacao CHECK (designacao ~ '^[0-9]{2}/[0-9]{2}$'),
    CONSTRAINT ck_pista_dimensoes CHECK (comprimento_m > 0 AND largura_m > 0),
    CONSTRAINT ck_pista_resistencia CHECK (
        (resistencia_kg IS NOT NULL AND resistencia_kg > 0
         AND resistencia_mpa IS NOT NULL AND resistencia_mpa > 0
         AND resistencia_pcn IS NULL)
        OR (resistencia_kg IS NULL AND resistencia_mpa IS NULL AND resistencia_pcn IS NOT NULL)
    )
);
CREATE INDEX idx_pista_aerodromo ON pista(aerodromo_id);
CREATE INDEX idx_pista_superficie ON pista(superficie_pista_id);
CREATE INDEX idx_pista_comprimento ON pista(comprimento_m);

-- 6. Operacao diurna/noturna: 'VFR / IFR' vira duas relacoes atomicas.
CREATE TABLE aerodromo_operacao (
    aerodromo_id INTEGER NOT NULL REFERENCES aerodromo(aerodromo_id) ON DELETE CASCADE,
    periodo VARCHAR(7) NOT NULL,
    tipo_operacao_id INTEGER NOT NULL REFERENCES tipo_operacao(tipo_operacao_id),
    CONSTRAINT pk_aerodromo_operacao PRIMARY KEY (aerodromo_id, periodo, tipo_operacao_id),
    CONSTRAINT ck_aerodromo_operacao_periodo CHECK (periodo IN ('DIURNO', 'NOTURNO'))
);
CREATE INDEX idx_aerodromo_operacao_tipo ON aerodromo_operacao(tipo_operacao_id);
CREATE INDEX idx_aerodromo_operacao_periodo ON aerodromo_operacao(periodo);

-- 7. Dados RBAC opcionais: 71 aerodromos; perfil NULL para 16 deles.
CREATE TABLE aerodromo_rbac (
    aerodromo_id INTEGER PRIMARY KEY REFERENCES aerodromo(aerodromo_id) ON DELETE CASCADE,
    classe_rbac153 SMALLINT NOT NULL,
    classe_rbac107 CHAR(4) NOT NULL,
    perfil_operacional_id INTEGER REFERENCES perfil_operacional(perfil_operacional_id),
    CONSTRAINT ck_rbac153 CHECK (classe_rbac153 IN (1, 2, 3)),
    CONSTRAINT ck_rbac107 CHECK (classe_rbac107 IN ('AP-0', 'AP-1', 'AP-2'))
);
CREATE INDEX idx_aerodromo_rbac_perfil ON aerodromo_rbac(perfil_operacional_id);

-- 8. Categoria derivada de operacao_internacional (coluna multivalorada).
CREATE TABLE aerodromo_categoria_operacao (
    aerodromo_id INTEGER NOT NULL REFERENCES aerodromo_rbac(aerodromo_id) ON DELETE CASCADE,
    categoria_operacao_id INTEGER NOT NULL REFERENCES categoria_operacao(categoria_operacao_id),
    CONSTRAINT pk_aerodromo_categoria_operacao PRIMARY KEY (aerodromo_id, categoria_operacao_id)
);
CREATE INDEX idx_aerodromo_categoria_operacao_categoria
    ON aerodromo_categoria_operacao(categoria_operacao_id);

-- 9. Restricoes: 19 vinculos, 8 descricoes distintas apos padronizacao.
CREATE TABLE aerodromo_restricao (
    aerodromo_id INTEGER NOT NULL REFERENCES aerodromo(aerodromo_id) ON DELETE CASCADE,
    restricao_id INTEGER NOT NULL REFERENCES restricao(restricao_id),
    CONSTRAINT pk_aerodromo_restricao PRIMARY KEY (aerodromo_id, restricao_id)
);
CREATE INDEX idx_aerodromo_restricao_restricao
    ON aerodromo_restricao(restricao_id);

COMMENT ON COLUMN aerodromo.aerodromo_id IS 'Fonte: id_aerodromo do CSV ANAC.';
COMMENT ON COLUMN aerodromo.municipio_id IS 'Fonte: municipio e uf do CSV.';
COMMENT ON COLUMN aerodromo.municipio_servido_id IS 'Fonte: municipio_servido e uf_servido do CSV.';
COMMENT ON COLUMN pista.pista_id IS 'Fonte: pista1_id do CSV ANAC.';
COMMENT ON TABLE aerodromo_operacao IS 'Decomposicao de operacao_diurna e operacao_noturna.';
COMMENT ON TABLE aerodromo_categoria_operacao IS 'Decomposicao da coluna operacao_internacional.';
COMMENT ON TABLE aerodromo_restricao IS 'Relaciona aerodromos aos textos padronizados de restricao.';
COMMIT;
